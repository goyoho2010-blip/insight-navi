# D-7 위험교재 판정 기준: 점검일까지 7일 이내 + 진도율 80% 미만
DANGER_DAYS = 7
DANGER_PROGRESS = 80


def _dday(check_date: date) -> int:
    return (check_date - DEMO_TODAY).days


def learning_rows(student_id: str) -> list[dict]:
    """교재별 계산값(D-day, 상태 배지)을 붙여 돌려준다."""
    rows = []
    for m in LEARNING[student_id]["materials"]:
        dday = _dday(m["check_date"])
        danger = dday <= DANGER_DAYS and m["progress"] < DANGER_PROGRESS
        if danger:
            status = "🚨 D-7 위험"
        elif dday <= DANGER_DAYS or m["progress"] < 60:
            status = "🟡 주의"
        else:
            status = "✅ 안정"
        row = dict(m)
        row.update(
            {
                "dday": dday,
                "dday_text": f"D-{dday}" if dday > 0 else ("D-DAY" if dday == 0 else f"D+{abs(dday)}"),
                "status": status,
                "danger": danger,
                "delta": m["progress"] - m["prev_progress"],
                "rounds_text": f"{m['current_rounds']}/{m['target_rounds']}회독",
            }
        )
        rows.append(row)
    return rows


def learning_kpis(student_id: str) -> dict:
    rows = learning_rows(student_id)
    avg = round(sum(r["progress"] for r in rows) / len(rows))
    prev = round(sum(r["prev_progress"] for r in rows) / len(rows))
    return {
        "completion": avg,
        "prev_completion": prev,
        "delta": avg - prev,
        "danger_count": sum(1 for r in rows if r["danger"]),
        "material_count": len(rows),
    }


